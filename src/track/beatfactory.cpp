const QString kRoundingVersion = QStringLiteral("V4");

struct ClockPhase {
    double phase;
    double coherence;
};

ClockPhase measurePhase(const std::vector<double>& times,
        double bpm,
        double harmonic) {
    double real = 0;
    double imaginary = 0;
    for (const double time : times) {
        const double angle = time * bpm * harmonic * 2 * M_PI / 60;
        real += std::cos(angle);
        imaginary += std::sin(angle);
    }
    return {std::atan2(imaginary, real) * 60 / (bpm * harmonic * 2 * M_PI),
            std::hypot(real, imaginary) / times.size()};
}

double percentile(const std::vector<double>& sorted, double fraction) {
    const double index = fraction * (sorted.size() - 1);
    const auto left = static_cast<size_t>(index);
    const auto right = std::min(left + 1, sorted.size() - 1);
    return sorted[left] + (index - left) * (sorted[right] - sorted[left]);
}

struct ConstantClockFit {
    mixxx::BeatsPointer grid;
    bool constant = false;
};

// Autonomously generated by an AI agent.
// Judge local clock continuity before pooling incompatible tracker phases.
// A nuisance phase step must also contain an abrupt beat-level displacement;
// a smooth excursion must not disappear just because it crosses a window edge.
// Unwrap at individual beats so smooth drift cannot alias between windows.
// These thresholds express timing tolerances, not calibrated probabilities.
// End of autonomously generated text.
struct ClockAssessment {
    bool constant = false;
    double phaseSpan = 0;
    size_t jumps = 0;
};

ClockAssessment assessClock(const std::vector<double>& times, double bpm) {
    const double period = 60 / bpm;
    std::vector<double> offsets(times.size());
    for (size_t i = 1; i < times.size(); ++i) {
        offsets[i] = offsets[i - 1] +
                std::remainder(times[i] - times[i - 1], period / 2);
    }
    struct Window {
        double time;
        double offset;
        double period;
        size_t block;
        size_t first;
        size_t last;
    };
    std::vector<Window> windows;
    size_t windowCount = 0;
    const auto windowBeats = std::min(size_t(32), times.size() / 4);
    for (size_t i = 0; i + std::max(size_t(8), windowBeats / 2) <= times.size(); i += windowBeats) {
        const auto end = std::min(i + windowBeats, times.size());
        const std::vector<double> block(times.begin() + i, times.begin() + end);
        const auto phase = measurePhase(block, bpm, 2);
        ++windowCount;
        if (phase.coherence >= 0.7) {
            windows.push_back({std::accumulate(block.begin(), block.end(), 0.0) / block.size(),
                    std::accumulate(offsets.begin() + i, offsets.begin() + end, 0.0) /
                            block.size(),
                    (block.back() - block.front()) / (block.size() - 1),
                    i / windowBeats,
                    i,
                    end});
        }
    }
    ClockAssessment result;
    if (windows.size() >= 4 && windows.size() >= 0.8 * windowCount &&
            windows.front().block == 0 && windows.back().block + 1 == windowCount) {
        double previous = windows.front().offset;
        double unwrapped = previous;
        double jumps = 0;
        const double jumpThreshold = std::max(0.04, period * 0.08);
        std::vector<double> increments(windows.size());
        for (size_t i = 1; i < windows.size(); ++i) {
            increments[i] = windows[i].offset - windows[i - 1].offset;
        }
        for (size_t i = 0; i < windows.size(); ++i) {
            const double current = windows[i].offset;
            if (i > 0) {
                const double delta = current - previous;
                unwrapped += delta;
                const auto continues = [delta](double neighbor) {
                    return neighbor * delta > 0 && std::abs(neighbor) >= std::abs(delta) * 0.5;
                };
                const bool acrossGap = windows[i].block > windows[i - 1].block + 1;
                const bool continuesBefore = continues(increments[i - 1]);
                const bool continuesAfter = i + 1 < increments.size() &&
                        continues(increments[i + 1]);
                bool abrupt = false;
                for (size_t beat = std::max(size_t(3), windows[i - 1].first + 1);
                        beat < windows[i].last && beat + 3 <= offsets.size() && !abrupt;
                        ++beat) {
                    if (std::abs(offsets[beat] - offsets[beat - 1]) <= jumpThreshold) {
                        continue;
                    }
                    std::array<double, 3> before{
                            offsets[beat - 3], offsets[beat - 2], offsets[beat - 1]};
                    std::array<double, 3> after{
                            offsets[beat], offsets[beat + 1], offsets[beat + 2]};
                    std::sort(before.begin(), before.end());
                    std::sort(after.begin(), after.end());
                    const double step = after[1] - before[1];
                    abrupt = std::abs(step) > jumpThreshold &&
                            std::abs(step - delta) <= jumpThreshold;
                }
                if (std::abs(delta) > jumpThreshold &&
                        (acrossGap || (!continuesBefore && !continuesAfter)) && abrupt) {
                    jumps += delta;
                    ++result.jumps;
                }
            }
            windows[i].offset = unwrapped - jumps;
            previous = current;
        }
        double meanTime = 0;
        double meanOffset = 0;
        std::vector<double> localPeriods;
        for (const auto& window : windows) {
            meanTime += window.time / windows.size();
            meanOffset += window.offset / windows.size();
            localPeriods.push_back(window.period);
        }
        const double startPeriod = (localPeriods[0] + localPeriods[1]) * 0.5;
        const double endPeriod =
                (localPeriods[localPeriods.size() - 2] + localPeriods.back()) *
                0.5;
        std::sort(localPeriods.begin(), localPeriods.end());
        const bool densityStable = percentile(localPeriods, 0.8) <=
                        1.25 * percentile(localPeriods, 0.2) &&
                std::max(startPeriod, endPeriod) <=
                        1.25 * std::min(startPeriod, endPeriod);
        double covariance = 0;
        double variance = 0;
        for (const auto& window : windows) {
            covariance += (window.time - meanTime) * (window.offset - meanOffset);
            variance += (window.time - meanTime) * (window.time - meanTime);
        }
        std::vector<double> deviations;
        for (const auto& window : windows) {
            deviations.push_back(window.offset - meanOffset -
                    covariance / variance * (window.time - meanTime));
        }
        const double startDeviation = (deviations[0] + deviations[1]) * 0.5;
        const double endDeviation = (deviations[deviations.size() - 2] + deviations.back()) * 0.5;
        std::sort(deviations.begin(), deviations.end());
        result.phaseSpan = percentile(deviations, 0.95) - percentile(deviations, 0.05);
        result.constant = densityStable && result.phaseSpan <= std::max(0.05, period * 0.1) &&
                std::max(std::abs(startDeviation), std::abs(endDeviation)) <=
                        std::max(0.04, period * 0.08);
    }
    return result;
}

// Autonomously generated by an AI agent.
// Select a supported phase neighborhood before averaging. Opposite metrical
// phases can cancel the fundamental, and averaging separate plateaus can place
// the output grid between both sets of observations.
// End of autonomously generated text.
double supportedPhase(const std::vector<double>& times,
        const std::vector<double>& sampled,
        double bpm) {
    const double period = 60 / bpm;
    std::vector<double> candidates{measurePhase(times, bpm, 1).phase};
    const size_t count = std::min(size_t(64), times.size() / 8);
    for (size_t i = 0; i < count; ++i) {
        const size_t first = i * (times.size() - 8) / std::max(size_t(1), count - 1);
        const std::vector<double> block(times.begin() + first, times.begin() + first + 8);
        const auto phase = measurePhase(block, bpm, 1);
        if (phase.coherence >= 0.7) {
            candidates.push_back(phase.phase);
        }
    }
    double phase = candidates.front();
    size_t bestCount = 0;
    double bestError = std::numeric_limits<double>::infinity();
    for (const double candidate : candidates) {
        size_t supported = 0;
        double error = 0;
        for (const double time : sampled) {
            const double residual = std::abs(std::remainder(time - candidate, period));
            if (residual <= 0.04) {
                ++supported;
                error += residual * residual;
            }
        }
        if (supported > bestCount || (supported == bestCount && error < bestError)) {
            phase = candidate;
            bestCount = supported;
            bestError = error;
        }
    }
    double adjustment = 0;
    size_t supported = 0;
    for (const double time : times) {
        const double residual = std::remainder(time - phase, period);
        if (std::abs(residual) <= 0.04) {
            adjustment += residual;
            ++supported;
        }
    }
    return supported ? phase + adjustment / supported : phase;
}

ConstantClockFit fitConstantClock(
        const QVector<mixxx::audio::FramePos>& beats,
        const mixxx::BeatsPointer& seed,
        const QHash<QString, QString>& extraVersionInfo,
        mixxx::audio::SampleRate sampleRate) {
    if (!seed || beats.size() < 32) {
        return {};
    }
    const double seedBpm = seed->getBpmAroundPosition(beats.front(), 1).value();
    const double duration = (beats.back() - beats.front()) / sampleRate;
    if (!(duration > 0) || !(seedBpm > 0)) {
        return {};
    }
    std::vector<double> times;
    times.reserve(beats.size());
    for (const auto beat : beats) {
        times.push_back((beat - beats.front()) / sampleRate);
    }
    std::vector<double> sampled;
    const int count = std::min(1024, static_cast<int>(times.size()));
    for (int i = 0; i < count; ++i) {
        sampled.push_back(times[static_cast<size_t>(i) * (times.size() - 1) / (count - 1)]);
    }
    double bpm = seedBpm;
    double radius = seedBpm * 0.008;
    double step = std::max(6.0 / duration, radius / 1024);
    for (int pass = 0; pass < 3; ++pass) {
        const double center = bpm;
        double best = -1;
        for (double candidate = center - radius;
                candidate <= center + radius + step * 0.1;
                candidate += step) {
            const auto phase = measurePhase(sampled, candidate, 2);
            if (phase.coherence > best) {
                best = phase.coherence;
                bpm = candidate;
            }
        }
        radius = step;
        step *= 0.1;
    }
    const double period = 60 / bpm;
    auto assessment = assessClock(times, bpm);

    std::vector<double> localTempos;
    for (size_t start = 0; start + 64 <= times.size(); start += 64) {
        const std::vector<double> block(times.begin() + start, times.begin() + start + 64);
        const auto localPhase = measurePhase(block, bpm, 1);
        double meanIndex = 0;
        double meanTime = 0;
        for (size_t i = start; i < start + 64; ++i) {
            meanIndex += std::round((times[i] - localPhase.phase) / period) / 64;
            meanTime += times[i] / 64;
        }
        double covariance = 0;
        double variance = 0;
        for (size_t i = start; i < start + 64; ++i) {
            const double index = std::round((times[i] - localPhase.phase) / period);
            covariance += (index - meanIndex) * (times[i] - meanTime);
            variance += (index - meanIndex) * (index - meanIndex);
        }
        if (!(variance > 0)) {
            continue;
        }
        const double slope = covariance / variance;
        bool stable = std::abs(slope / period - 1) < 0.008;
        for (size_t i = start; stable && i < start + 64; ++i) {
            const double index = std::round((times[i] - localPhase.phase) / period);
            stable = std::abs(times[i] - meanTime - slope * (index - meanIndex)) <= 0.04;
        }
        if (stable) {
            localTempos.push_back(60 / slope);
        }
    }
    if (localTempos.size() >= 4) {
        std::sort(localTempos.begin(), localTempos.end());
        const auto trim = localTempos.size() / 10;
        const double localBpm = std::accumulate(localTempos.begin() + trim,
                                        localTempos.end() - trim,
                                        0.0) /
                (localTempos.size() - trim * 2);
        const auto localAssessment = assessClock(times, localBpm);
        if (assessment.jumps > 0 || std::abs(bpm / localBpm - 1) * duration <= 0.025 ||
                (localAssessment.constant && !assessment.constant)) {
            bpm = localBpm;
            assessment = localAssessment;
        }
    }
    const double phase = supportedPhase(times, sampled, bpm);
    double first = std::fmod(beats.front().value() + phase * sampleRate,
            60 * sampleRate / bpm);
    if (first < 0) {
        first += 60 * sampleRate / bpm;
    }
    auto grid = mixxx::Beats::fromConstTempo(sampleRate,
            mixxx::audio::FramePos(first).toNearestFrameBoundary(),
            mixxx::Bpm(bpm),
            BeatFactory::getPreferredSubVersion(extraVersionInfo));
    qDebug() << "Auto clock fit:" << bpm << "BPM; coherence"
             << measurePhase(times, bpm, 2).coherence << "phase span"
             << assessment.phaseSpan * 1000 << "ms; constant"
             << assessment.constant;
    return {grid, assessment.constant};
}

